const dict: Record<Lang, Record<Key, string>> = { uz, ru };

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>) {
  const text = dict[lang]?.[key] ?? uz[key] ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? '')) : text;
}

export function useT() {
  const lang = usePrefs((s) => s.lang);
  return (key: Key, vars?: Record<string, string | number>) => translate(lang, key, vars);
}

/** Mahsulot/kategoriya maydonini tilga qarab olish: pick(p, 'name', lang) → nameUz | nameRu */
export function pick<T extends object>(obj: T, field: string, lang: Lang): string {
  const record = obj as Record<string, unknown>;
  const value = record[`${field}${lang === 'ru' ? 'Ru' : 'Uz'}`] ?? record[`${field}Uz`];
  return typeof value === 'string' ? value : '';
}
